OK_SAME = {"回饋", "大盤指數", "優化"}


def check_text(text):
    plain = re.sub(r"<[^>]+>", "", text)
    simp = sorted({ch for ch in plain if ch in SIMPLIFIED})
    terms = [(k, v) for k, v in MAINLAND_TERMS.items() if k in plain and k not in OK_SAME]
    return simp, terms


def char_count(html):
    """공백·태그 제외 글자 수"""
    plain = re.sub(r"<[^>]+>", "", html)
    return len(re.sub(r"\s", "", plain))
